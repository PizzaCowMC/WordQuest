export function getSpecialMobForCity(
  cityName: string,
  baseCoords: [number, number]
): Monster | null {
  const match = SPECIAL_MOB_TEMPLATES.find(
    (t) => cityName.toLowerCase().includes(t.cityMatch.toLowerCase())
  );
  if (!match) return null;

  // Build 5 super challenging questions: 3 Extreme C2 + 2 Typing questions
  const qList = [
    {
      ...SUPER_CHALLENGING_QUESTIONS[Math.floor(Math.random() * SUPER_CHALLENGING_QUESTIONS.length)],
      id: `${match.id}-q1`,
      moveName: 'Mythic Grammar Inversion',
    },
    {
      ...TYPING_QUESTIONS[Math.floor(Math.random() * TYPING_QUESTIONS.length)],
      id: `${match.id}-q2`,
      moveName: 'Glyph Typing Trial',
    },
    {
      ...SUPER_CHALLENGING_QUESTIONS[(Math.floor(Math.random() * SUPER_CHALLENGING_QUESTIONS.length) + 1) % SUPER_CHALLENGING_QUESTIONS.length],
      id: `${match.id}-q3`,
      moveName: 'C2 Lexicon Cataclysm',
    },
    {
      ...TYPING_QUESTIONS[(Math.floor(Math.random() * TYPING_QUESTIONS.length) + 3) % TYPING_QUESTIONS.length],
      id: `${match.id}-q4`,
      moveName: 'Orthography Strike',
    },
    {
      ...SUPER_CHALLENGING_QUESTIONS[(Math.floor(Math.random() * SUPER_CHALLENGING_QUESTIONS.length) + 7) % SUPER_CHALLENGING_QUESTIONS.length],
      id: `${match.id}-q5`,
      moveName: 'Mythic Apotheosis',
    },
  ];

  return {
    id: match.id,
    name: match.name,
    type: match.type,
    level: 150,
    hp: 5,
    maxHp: 5,
    position: [baseCoords[0] + match.offset[0], baseCoords[1] + match.offset[1]],
    streetName: match.streetName,
    spriteColor: match.spriteColor,
    auraColor: match.auraColor,
    description: match.description,
    avatarIcon: match.avatarIcon,
    rarity: 'Mythic',
    lessonTopic: `Mythic Encounter: ${match.name}`,
    questions: qList,
  };
}
